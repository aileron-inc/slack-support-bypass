#!/usr/bin/env node
/**
 * Copy ~/.slack-support-bypass/{routes.json,secrets.env} into .dev.vars.
 * The Worker never reads the home directory at runtime; wrangler injects env.
 */
import { homedir } from "node:os";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const homeDir = process.env.SLACK_SUPPORT_BYPASS_HOME
  ? process.env.SLACK_SUPPORT_BYPASS_HOME
  : join(homedir(), ".slack-support-bypass");
const routesPath = join(homeDir, "routes.json");
const secretsPath = join(homeDir, "secrets.env");
const outPath = join(root, ".dev.vars");

function dotenvEscape(value) {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

if (!existsSync(routesPath) || !existsSync(secretsPath)) {
  console.error(
    `Missing home-dir config.\n` +
      `  expected: ${routesPath}\n` +
      `            ${secretsPath}\n` +
      `Expected operator files (not in git):\n` +
      `  ~/.slack-support-bypass/routes.json\n` +
      `  ~/.slack-support-bypass/secrets.env`,
  );
  process.exit(1);
}

const routesRaw = readFileSync(routesPath, "utf8");
let parsed;
try {
  parsed = JSON.parse(routesRaw);
} catch {
  console.error(`${routesPath} is not valid JSON`);
  process.exit(1);
}

const routes = Array.isArray(parsed) ? parsed : parsed?.routes;
if (!Array.isArray(routes) || routes.length === 0) {
  console.error(`${routesPath} must be { "routes": [ ... ] } with at least one row`);
  process.exit(1);
}

const secrets = readFileSync(secretsPath, "utf8").replace(/\s+$/, "");
const lines = [
  "# Generated by npm run sync-config. Do not commit.",
  `# Source: ${homeDir}`,
  `ROUTES_JSON=${dotenvEscape(JSON.stringify(parsed))}`,
  secrets,
  "",
];

writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote ${outPath} (${routes.length} routes, secrets not printed)`);
